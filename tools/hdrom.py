"""Builds the Winchester coupler's option ROM (src/hw/guest/hdrom.asm, MezinXT's own) with tools/asm86.py.

    python tools/hdrom.py           writes src/hw/guest/hdrom.c (8 KiB: 55h AAh, 16 blocks, checksum byte last)
    python tools/hdrom.py --check   exit 1 when hdrom.c is not what the source assembles to

The ROM's bytes are committed as a C array beside the source, so building MezinXT needs no assembler; this
tool is run after the source changes (--check finds a stale array). MezinXT's own code.
"""

from __future__ import annotations

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from asm86 import assemble  # noqa: E402

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "src" / "hw" / "guest" / "hdrom.asm"
OUTPUT = ROOT / "src" / "hw" / "guest" / "hdrom.c"
SIZE = 8192


def build() -> bytes:
    code = bytearray(assemble(SOURCE.read_text(encoding="utf-8")))
    if len(code) > SIZE - 1:
        raise SystemExit(f"hdrom.asm assembles to {len(code)} bytes, more than {SIZE - 1}")
    if code[:3] != bytes([0x55, 0xAA, SIZE // 512]):
        raise SystemExit("hdrom.asm does not start with 55h AAh and its size in 512-byte blocks")
    code += b"\xFF" * (SIZE - len(code))          # an EPROM's erased cells
    code[-1] = 0
    code[-1] = -sum(code) & 255
    return bytes(code)


def c_source(rom: bytes) -> str:
    lines = ["/* MezinXT's option ROM for the Winchester coupler (hdc.h): generated by tools/hdrom.py from",
             " * src/hw/guest/hdrom.asm, MezinXT's own code. Do not edit; run python tools/hdrom.py after changing the",
             " * source. */",
             '#include "../hdc.h"',
             "",
             "const uint8_t mx_hdc_rom[MX_HDC_ROM_SIZE] = {"]
    for i in range(0, len(rom), 16):
        lines.append("    " + ", ".join(f"0x{b:02X}" for b in rom[i:i + 16]) + ",")
    lines.append("};")
    return "\n".join(lines) + "\n"


def main(argv: list[str]) -> int:
    text = c_source(build())
    if "--check" in argv:
        if not OUTPUT.is_file() or OUTPUT.read_text(encoding="utf-8") != text:
            print(f"{OUTPUT.relative_to(ROOT)} is stale: python tools/hdrom.py")
            return 1
        return 0
    OUTPUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"{OUTPUT.relative_to(ROOT)}: {SIZE} bytes")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
